/**
 * Files on a support thread.
 *
 * Theo Cliche, 2026-09-04, mid-thread about an upload that would not work: "It also does
 * not allow me to send you pictures on this log". The one thing that would have told us
 * what was wrong with his receipt was the one thing the thread could not carry.
 *
 * THE FILE DOES NOT GO THROUGH OUR API, AND THAT IS THE WHOLE DESIGN
 *
 * Mirae, 2026-09-08: "근데 여기도 파일제한 있으면 먼소영". Right. Vercel refuses a
 * serverless function request body over 4.5 MB before our code runs, which is what broke
 * Theo's receipt upload to begin with. An attachment posted the same way would hit the
 * same wall, and the file somebody most needs to show us is exactly the one that is too
 * big to send.
 *
 * So: the browser asks us for a short-lived signed upload URL, PUTs the file straight to
 * Supabase Storage, and sends back only the key. Nothing but JSON crosses our function.
 *
 * WHAT THAT COSTS, AND WHO PAYS IT
 *
 * We never see the bytes, so we cannot check them. Every limit therefore lives on the
 * `support` bucket itself, where Storage enforces it whatever the client does: private,
 * 20 MB, and an image/PDF allowlist. The checks in this file are for telling the person a
 * useful thing before they wait for an upload, not for security. Treat them as a courtesy
 * and the bucket as the rule.
 */

/** Enforced by the bucket. Repeated here only so the page can say so up front. */
export const SUPPORT_MAX_BYTES = 20 * 1024 * 1024
export const SUPPORT_MAX_LABEL = '20 MB'

/**
 * Also enforced by the bucket. HEIC is here and deliberately not in the receipt uploader:
 * a support attachment only has to be looked at by a person, while a receipt has to be
 * read by a model, so the formats we can accept are not the same set.
 */
export const SUPPORT_ALLOWED_MIME = [
  'image/jpeg',
  'image/png',
  'image/webp',
  'image/heic',
  'application/pdf'
] as const

export const SUPPORT_BUCKET = 'support'

/** Renders inline in the thread rather than as a link to open. */
export function isViewableImage(mime: string | null | undefined): boolean {
  const m = (mime ?? '').toLowerCase()
  // HEIC is allowed for upload because that is what an iPhone hands over, but no desktop
  // browser will paint it in an <img>, so it gets the link treatment.
  return m === 'image/jpeg' || m === 'image/png' || m === 'image/webp'
}

/**
 * Why this file cannot be attached, or null when it can.
 *
 * Deliberately says what to do next. "Unsupported file type" tells somebody who just
 * failed at uploading a receipt nothing they did not already know.
 */
export function attachmentProblem(
  file: { name?: string; type?: string; size?: number } | null | undefined
): string | null {
  if (!file) return 'No file was picked.'
  const size = Number(file.size ?? 0)
  if (!Number.isFinite(size) || size <= 0) {
    return 'That file came through empty. Please pick it again, or take a new photo.'
  }
  if (size > SUPPORT_MAX_BYTES) {
    return `That file is ${(size / 1_000_000).toFixed(1)} MB, over the ${SUPPORT_MAX_LABEL} limit.`
  }
  const mime = (file.type ?? '').toLowerCase()
  if (!(SUPPORT_ALLOWED_MIME as readonly string[]).includes(mime)) {
    return 'You can attach a photo (JPG, PNG, WebP, HEIC) or a PDF.'
  }
  return null
}

/** The extension to keep on the stored object, chosen from the type rather than the name. */
function extensionFor(mime: string): string {
  switch (mime.toLowerCase()) {
    case 'image/jpeg': return 'jpg'
    case 'image/png': return 'png'
    case 'image/webp': return 'webp'
    case 'image/heic': return 'heic'
    case 'application/pdf': return 'pdf'
    default: return 'bin'
  }
}

/**
 * Where the object goes: `<bamId>/<questionId>/<random>.<ext>`.
 *
 * Generated, never derived from what the student called the file. A filename arrives from
 * outside and can contain a path, so building a key out of one is how an upload lands
 * somewhere it was not meant to. The original name is kept in a column instead, where it
 * is data rather than a path.
 *
 * The BAM id leads so a key can be checked against a session without a database round
 * trip, the same shape the receipts bucket uses.
 */
export function buildAttachmentKey(args: {
  bamId: string
  questionId: string
  mime: string
  random?: string
}): string {
  const rand = args.random ?? globalThis.crypto.randomUUID()
  return `${args.bamId}/${args.questionId}/${rand}.${extensionFor(args.mime)}`
}

/** Does this key belong to this BAM? The prefix is the answer, and it is generated by us. */
export function keyBelongsToBam(key: string, bamId: string): boolean {
  if (!key || !bamId) return false
  return key.startsWith(`${bamId}/`)
}

/**
 * A filename safe to put in a Content-Disposition header.
 *
 * The stored name came from the student's device. Quotes and newlines in a header value
 * are how a download filename turns into a second header.
 */
/** The columns a message carries when a file came with it. */
export type AttachmentColumns = {
  attachment_key: string
  attachment_mime: string
  attachment_bytes: number | null
  attachment_name: string | null
}

export type AttachmentInput =
  | { ok: true; columns: AttachmentColumns | null }
  | { ok: false; message: string }

/**
 * Turns whatever the client posted alongside a message into columns, or refuses it.
 *
 * The key is the part that matters. It was minted by the attachment route under this
 * student's own prefix, and it travels back through the client, so it has to be checked
 * against the session again here. Without that a message could claim any key in the
 * bucket, and the thread would serve someone else's file to whoever opened it.
 *
 * No attachment is the normal case and is not an error.
 */
export function parseAttachmentInput(raw: unknown, bamId: string): AttachmentInput {
  if (raw === undefined || raw === null) return { ok: true, columns: null }
  if (typeof raw !== 'object') return { ok: false, message: 'That attachment did not come through.' }

  const a = raw as Record<string, unknown>
  const key = typeof a.key === 'string' ? a.key.trim() : ''
  const mime = typeof a.mime === 'string' ? a.mime.trim().toLowerCase() : ''
  if (!key && !mime) return { ok: true, columns: null }

  if (!key || !mime) return { ok: false, message: 'That attachment did not come through.' }
  if (!(SUPPORT_ALLOWED_MIME as readonly string[]).includes(mime)) {
    return { ok: false, message: 'You can attach a photo (JPG, PNG, WebP, HEIC) or a PDF.' }
  }
  if (!keyBelongsToBam(key, bamId)) {
    return { ok: false, message: 'That attachment is not yours.' }
  }

  const bytes = Number(a.bytes)
  const name = typeof a.name === 'string' ? a.name.slice(0, 200) : null
  return {
    ok: true,
    columns: {
      attachment_key: key,
      attachment_mime: mime,
      attachment_bytes: Number.isFinite(bytes) && bytes > 0 ? Math.round(bytes) : null,
      attachment_name: name
    }
  }
}

export function safeDownloadName(name: string | null | undefined, mime: string): string {
  const fallback = `attachment.${extensionFor(mime)}`
  if (!name) return fallback
  const cleaned = name
    .replace(/[\r\n"\\]/g, '')
    .replace(/[/\\]/g, '-')
    .trim()
    .slice(0, 120)
  return cleaned.length > 0 ? cleaned : fallback
}
